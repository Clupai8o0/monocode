/**
 * Fork: every picture at the table, as rows of pixels. '.' stays empty and any
 * other character picks a colour when it's drawn. Two frames where things move.
 */

export type Rows = readonly string[];

const pathCache = new Map<string, string>();

/** One path of runs for the pixels drawn with `char`. */
export function rowsPath(rows: Rows, char: string) {
  const key = `${char}|${rows.join("/")}`;
  const cached = pathCache.get(key);
  if (cached !== undefined) {
    return cached;
  }
  let path = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== char) {
        x += 1;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === char) {
        end += 1;
      }
      path += `M${x} ${y}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  pathCache.set(key, path);
  return path;
}

