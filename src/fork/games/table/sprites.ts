export const CARD_W = 15;
export const CARD_H = 21;

/** A card's shape: a full block with the corners nibbled away. */
export const CARD_SHAPE: Rows = Array.from({ length: CARD_H }, (_, y) => {
  const inset = y === 0 || y === CARD_H - 1 ? 2 : y === 1 || y === CARD_H - 2 ? 1 : 0;
  return ".".repeat(inset) + "#".repeat(CARD_W - inset * 2) + ".".repeat(inset);
});

function stamp(grid: string[][], rows: Rows, left: number, top: number) {
  rows.forEach((row, y) => {
    [...row].forEach((pixel, x) => {
      if (pixel !== ".") {
        grid[top + y]![left + x] = "#";
      }
    });
  });
}

const faceCache = new Map<Card, Rows>();

/** The ink on a card's face: its rank, a small suit and a large one. */
export function cardInk(card: Card): Rows {
  const cached = faceCache.get(card);
  if (cached) {
    return cached;
  }
  const grid = Array.from({ length: CARD_H }, () =>
    new Array<string>(CARD_W).fill("."),
  );
  const suit = suitOf(card);
  stamp(grid, RANK_GLYPHS[rankName(card)]!, 2, 2);
  stamp(grid, SUIT_SMALL[suit]!, 2, 8);
  stamp(grid, SUIT_BIG[suit]!, 7, 13);
  const rows = grid.map((row) => row.join(""));
  faceCache.set(card, rows);
  return rows;
}

export function inkColor(card: Card) {
  return isRed(card) ? "var(--table-red)" : "var(--color-content)";
}

const MARK: Rows = ["#.....#", "##...##", "#.#.#.#", "#..#..#", "#.....#"];

/** The back: the dotted grid, cleared around a small MonoCode mark. */
export const CARD_BACK_DOTS: Rows = Array.from({ length: CARD_H }, (_, y) =>
  Array.from({ length: CARD_W }, (_, x) => {
    const inMark = x >= 3 && x <= 11 && y >= 7 && y <= 13;
    const edge = x < 2 || x > CARD_W - 3 || y < 2 || y > CARD_H - 3;
    return !inMark && !edge && x % 2 === 0 && y % 2 === 0 ? "#" : ".";
  }).join(""),
);

export const CARD_BACK_MARK: Rows = (() => {
  const grid = Array.from({ length: CARD_H }, () =>
    new Array<string>(CARD_W).fill("."),
  );
  stamp(grid, MARK, 4, 8);
  return grid.map((row) => row.join(""));
})();

